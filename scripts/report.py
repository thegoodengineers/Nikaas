"""Generate docs/RESULTS.md from runs/*.csv so the numbers shown to judges cannot drift.
Latest run per (building, plan, blocked) wins."""
import csv
import json

NL = chr(10)
from pathlib import Path

rows = {}
for f in sorted(Path("runs").glob("results*.csv")):
    for r in csv.DictReader(f.open(encoding="utf-8")):
        rows[(r["building"], r["plan"], r["blocked"])] = r
out = ["# Results (generated by `scripts/report.py` from `runs/*.csv`; do not edit by hand)", "",
       "| Building | Plan | Blocked exit | People | Evacuation time (s) | People per exit | Bottleneck (peak queue) | Commit |",
       "|---|---|---|---|---|---|---|---|"]
for (b, p, bl), r in sorted(rows.items()):
    out.append(f"| {b} | {p} | {bl or '-'} | {r['people']} | {r['total_time_s'] or 'did not finish in 1800 s'} | {r['per_exit']} | {r['bottleneck']} ({r['peak_queue']}) | {r['commit']} |")
Path("docs/RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out))

# same numbers for the website (landing-page stats), so the site cannot drift from runs/ either
web = Path("web/public/data")
if web.exists():
    json.dump([{"building": b, "plan": p, "blocked": bl, "people": int(r["people"]), "total_time_s": float(r["total_time_s"]) if r["total_time_s"] else None,  # empty = did not finish
                "bottleneck": r["bottleneck"], "peak_queue": int(r["peak_queue"]), "commit": r["commit"]}
               for (b, p, bl), r in sorted(rows.items())], (web / "results.json").open("w"), indent=1)

# optimiser results (Ayush, scripts/run_wow.py -> runs/wow.csv): latest row per (building, blocked)
wow = {}
if Path("runs/wow.csv").exists():
    for r in csv.DictReader(Path("runs/wow.csv").open(encoding="utf-8")):
        wow[(r["building"], r["blocked"])] = r
if wow:
    extra = ["", "## Nikaas plan vs nearest exit (`runs/wow.csv`)", "",
             "| Building | Blocked exit | People | Nearest exit (s) | Nikaas plan (s) | Saved (s) | Saved (%) | Lower bound (s) | Gap to bound (s) | Commit |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for (b, bl), r in sorted(wow.items()):
        extra.append(f"| {b} | {bl} | {r['total_people']} | {r['nearest_s']} | {r['optimised_s']} | {r['saved_s']} | {r['pct_saved']} | {r['lower_bound_s']} | {r['gap_to_bound_s']} | {r['commit']} |")
    md = Path("docs/RESULTS.md")
    md.write_text(md.read_text(encoding="utf-8") + NL.join(extra) + NL, encoding="utf-8")
    if web.exists():
        json.dump([{"building": b, "blocked": "" if bl == "-" else bl, "people": int(r["total_people"]), "nearest_s": float(r["nearest_s"]),
                    "nikaas_s": float(r["optimised_s"]), "saved_s": float(r["saved_s"]), "pct_saved": float(r["pct_saved"]),
                    "lower_bound_s": float(r["lower_bound_s"]), "gap_s": float(r["gap_to_bound_s"])} for (b, bl), r in sorted(wow.items())],
                  (web / "wow.json").open("w"), indent=1)
    print(NL.join(extra))

# the scale story (scripts/precompute_stadium.py -> runs/stadium_results.csv): stadium scaled to ~2,000 people
st = Path("runs/stadium_results.csv")
if st.exists():
    srows = list(csv.DictReader(st.open(encoding="utf-8")))
    extra = ["", "## Stadium, scaled to ~2,000 people (`runs/stadium_results.csv`)", "",
             "| Plan | People | Evacuation time (s) | Peak density (p/m²) | Worst edge | Lower bound (s) | Commit |",
             "|---|---|---|---|---|---|---|"]
    extra += [f"| {r['plan']} | {r['people']} | {r['total_time_s']} | {r['max_density_pm2']} | {r['worst_edge']} | {r['lower_bound_s'] or '-'} | {r.get('commit', '-')} |" for r in srows]
    md = Path("docs/RESULTS.md")
    md.write_text(md.read_text(encoding="utf-8") + NL.join(extra) + NL, encoding="utf-8")
    if web.exists():
        json.dump([{"plan": r["plan"], "people": int(r["people"]), "total_time_s": float(r["total_time_s"]),
                    "max_density": float(r["max_density_pm2"]), "worst_edge": r["worst_edge"],
                    "lower_bound_s": float(r["lower_bound_s"]) if r["lower_bound_s"] else None} for r in srows],
                  (web / "stadium.json").open("w"), indent=1)
    print(NL.join(extra))

# multi-floor buildings (Ayush, scripts/run_multi_floor.py -> runs/multi_floor.csv)
mf = Path("runs/multi_floor.csv")
if mf.exists():
    mrows = list(csv.DictReader(mf.open(encoding="utf-8")))
    nik = lambda r: r["plan_type"] == "nikaas_plan"  # blocked scenarios were run with the nearest-exit plan only
    extra = ["", "## Multi-floor buildings (`runs/multi_floor.csv`)", "",
             "| Scenario | Floors | People | Blocked | Nearest exit (s) | Nikaas plan (s) | Lower bound (s) | Commit |",
             "|---|---|---|---|---|---|---|---|"]
    extra += [f"| {r['scenario']} | {r['floor_count']} | {r['total_occupants']} | {r['blocked_resources']} | {r['nearest_time_s']} | "
              f"{r['movement_time_s'] if nik(r) else '-'} | {r['lower_bound_s']} | {r['commit']} |" for r in mrows]
    md = Path("docs/RESULTS.md")
    md.write_text(md.read_text(encoding="utf-8") + NL.join(extra) + NL, encoding="utf-8")
    if web.exists():
        json.dump([{"scenario": r["scenario"], "floors": int(r["floor_count"]), "people": int(r["total_occupants"]),
                    "blocked": "" if r["blocked_resources"] == "none" else r["blocked_resources"],
                    "nearest_s": float(r["nearest_time_s"]), "nikaas_s": float(r["movement_time_s"]) if nik(r) else None,
                    "lower_bound_s": float(r["lower_bound_s"])} for r in mrows], (web / "multi_floor.json").open("w"), indent=1)
    print(NL.join(extra))

# robustness (scripts/monte_carlo.py -> runs/monte_carlo_summary.csv): random pre-movement and occupancy
mc = Path("runs/monte_carlo_summary.csv")
if mc.exists():
    crows = list(csv.DictReader(mc.open(encoding="utf-8")))
    extra = ["", "## Under uncertainty (`runs/monte_carlo_summary.csv`)", "",
             "Times from the alarm (pre-movement uniform in [0, max] s per person, room occupancy scaled by 1 ± spread); plans fixed beforehand.", "",
             "| Building | Runs | Pre-movement max (s) | Occupancy ± | Nearest p50 / p95 (s) | Nikaas p50 / p95 (s) | Nikaas faster | Ties | Nikaas slower | Median saving (s) | Commit |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    extra += [f"| {r['building']} | {r['runs']} | {r['premove_max_s']} | {r['occupancy_spread']} | {r['nearest_p50_s']} / {r['nearest_p95_s']} | "
              f"{r['nikaas_p50_s']} / {r['nikaas_p95_s']} | {r['nikaas_faster']} | {r['ties']} | {r['nikaas_slower']} | {r['median_saving_s']} | {r['commit']} |" for r in crows]
    md = Path("docs/RESULTS.md")
    md.write_text(md.read_text(encoding="utf-8") + NL.join(extra) + NL, encoding="utf-8")
    # the runs where the nearest-exit rule wins: how many people turned up, and by how much the plan lost
    det = list(csv.DictReader(Path("runs/monte_carlo.csv").open(encoding="utf-8")))
    for r in crows:
        nominal = sum(n.get("people", 0) for n in json.loads(Path("data", r["building"]).read_text(encoding="utf-8-sig"))["nodes"] if n.get("type") == "room")
        lost = [d for d in det if d["building"] == r["building"] and float(d["nikaas_s"]) > float(d["nearest_s"]) + 0.01]
        loss = sorted(float(d["nikaas_s"]) - float(d["nearest_s"]) for d in lost)
        r.update(nominal_people=nominal, lost_people_min=min((int(d["people"]) for d in lost), default=0),
                 lost_people_max=max((int(d["people"]) for d in lost), default=0),
                 loss_median_s=loss[len(loss) // 2] if loss else 0, loss_max_s=loss[-1] if loss else 0)
        if lost:
            extra.append(f"- {r['building']}: in the {len(lost)} runs where the nearest-exit rule wins, {r['lost_people_min']}-{r['lost_people_max']} people "
                         f"were in the building (planned for {nominal}); the plan lost by {r['loss_median_s']} s at the median, {r['loss_max_s']} s at most.")
    md.write_text(md.read_text(encoding="utf-8") + NL + NL.join(extra[-sum(1 for r in crows if r['lost_people_max']):]) + NL, encoding="utf-8")
    if web.exists():
        json.dump([{k: (v if k in ("building", "commit") else float(v)) for k, v in r.items()} for r in crows],
                  (web / "monte_carlo.json").open("w"), indent=1)
    print(NL.join(extra))

